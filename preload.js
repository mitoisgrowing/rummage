const { contextBridge, ipcRenderer: r, webUtils } = require('electron');
contextBridge.exposeInMainWorld('api', {
  importFiles: files => r.invoke('import', [...files].map(f => webUtils.getPathForFile(f)).filter(Boolean)),
  scan: () => r.invoke('scan'),
  db: () => r.invoke('db'),
  roots: () => r.invoke('roots'),
  patch: (type, id, val) => r.invoke('patch', { type, id, val }),
  set: (k, v) => r.invoke('set', k, v),
  addFolder: () => r.invoke('addFolder'),
  rmFolder: f => r.invoke('rmFolder', f),
  pickBg: () => r.invoke('pickBg'),
  saveWav: (name, data) => r.invoke('saveWav', name, data),
  read: p => r.invoke('read', p),
  drag: p => r.send('drag', p),
  live: n => r.send('live', n),
  reveal: p => r.send('reveal', p),
  top: v => r.send('top', v),
  zoom: s => r.send('zoom', s),
  titlebar: c => r.send('titlebar', c),
  openRepo: () => r.send('openRepo'),
  openLoopMidi: () => r.send('openLoopMidi'),
  rewatch: () => r.send('rewatch'),
  onChanged: cb => r.on('changed', cb),
  onDaws: cb => r.on('daws', (_, v) => cb(v)),
  paths: () => r.invoke('paths'),
  pathAdd: (key, replace) => r.invoke('pathAdd', key, replace),
  pathRm: (key, p) => r.invoke('pathRm', key, p),
  pathReset: key => r.invoke('pathReset', key),
  openFst: p => r.send('openFst', p),
  dock: (host, side) => r.send('dock', host, side),
  onSide: cb => r.on('side', (_, v) => cb(v)),
  importPaths: paths => r.invoke('import', paths),
  onDocked: cb => r.on('docked', (_, v) => cb(v)),
  shots: () => r.invoke('shots'),
  shotSave: (key, dataUrl) => r.invoke('shotSave', key, dataUrl),
  shotPick: key => r.invoke('shotPick', key),
  shotDelete: key => r.invoke('shotDelete', key),
  shotScan: (list, retry) => r.invoke('shotScan', list, retry),
  shotStop: () => r.send('shotStop'),
  dawScript: host => r.invoke('dawScript', host),
  snips: () => r.invoke('snips'),
  snipSave: (id, buf) => r.invoke('snipSave', id, buf),
  snipDelete: id => r.invoke('snipDelete', id),
  dawTitle: host => r.invoke('dawTitle', host),
  onShotProgress: cb => r.on('shotProgress', (_, v) => cb(v)),
  capStart: (host, list, opts) => r.invoke('capStart', host, list, opts),
  capStop: () => r.invoke('capStop'),
  capSnap: (host, key, name) => r.invoke('capSnap', host, key, name),
  onCap: cb => r.on('cap', (_, v) => cb(v)),
});
